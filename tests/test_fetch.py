    path = _project_with_reference(tmp_path, "['https://youtu.be/broken', 'https://youtu.be/ok']")
    assert fetch.fetch(path).downloaded == [fetch.REFERENCE_ID]
    assert (tmp_path / "reference" / "reference.mp4").exists()


