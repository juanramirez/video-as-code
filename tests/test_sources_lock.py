"""sources_lock.py: the capture time it records and the local file name
derived from it - the bits fetch's tests only exercise at the epoch."""
from __future__ import annotations

from pathlib import Path

from video_as_code import sources_lock


def test_taken_local_uses_the_wall_time_where_it_was_taken():
    # 2025-08-30 23:30 UTC at UTC+2 is already the 31st locally
    utc_ms = 1756596600000
    assert sources_lock.taken_local(utc_ms, 7200000) == "2025-08-31T01:30:00"
    assert sources_lock.taken_local(utc_ms, -3600000) == "2025-08-30T22:30:00"


def test_local_name_is_capture_date_and_id_with_a_lowercase_extension():
    entry = {"taken": "2025-08-31T01:30:00"}
    assert sources_lock.local_name("slide", "IMG_1.JPG", entry) == "20250831_slide.jpg"


def test_local_name_override_wins():
    entry = {"taken": "2025-08-31T01:30:00"}
    assert sources_lock.local_name("slide", "IMG_1.jpg", entry, "my_name.jpg") == "my_name.jpg"


def test_local_name_falls_back_to_the_original_name_without_a_date():
    assert sources_lock.local_name("slide", "IMG_1.jpg", None) == "IMG_1.jpg"
    assert sources_lock.local_name("slide", "IMG_1.jpg", {"media_id": "x"}) == "IMG_1.jpg"


def test_write_then_read_round_trips_sorted_with_a_header(tmp_path: Path):
    entries = {
        "b.mp4": {"media_id": "m2", "size": 2, "sha256": "bb", "taken": "2025-08-31T01:30:00"},
        "a.jpg": {"media_id": "m1", "size": 1, "sha256": "aa", "taken": "2025-08-30T10:00:00"},
    }
    sources_lock.write(tmp_path, entries)
    text = (tmp_path / sources_lock.LOCK_NAME).read_text(encoding="utf-8")
    assert text.startswith("# Generated by")
    assert text.index("a.jpg") < text.index("b.mp4")
    assert sources_lock.read(tmp_path) == entries


def test_read_without_a_lock_is_empty(tmp_path: Path):
    assert sources_lock.read(tmp_path) == {}


def test_writing_one_section_keeps_the_other(tmp_path: Path):
    items = {"a.jpg": {"media_id": "m1", "size": 1, "sha256": "aa", "taken": "2025-08-30T10:00:00"}}
    links = {"music": {"url": "https://youtu.be/x", "ext": ".m4a", "size": 3, "sha256": "cc"}}
    sources_lock.write(tmp_path, items)
    sources_lock.write(tmp_path, links=links)
    assert sources_lock.read(tmp_path) == items
    sources_lock.write(tmp_path, {})
    assert sources_lock.read_links(tmp_path) == links


def test_link_local_name():
    assert sources_lock.link_local_name("music", {"ext": ".m4a"}) == "music.m4a"
    assert sources_lock.link_local_name("music", None) == "music"  # not downloaded yet
    assert sources_lock.link_local_name("music", {"ext": ".m4a"}, "song.m4a") == "song.m4a"
