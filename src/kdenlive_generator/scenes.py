"""Compiles the high-level `scenes:` YAML into explicit tracks/clips of the
low-level model (`timeline.tracks`), which is what `schema.validate_and_resolve`
validates and resolves.

A "scene" is a list of clips that play one after another. Its duration is
computed automatically (via `pacing`, or by splitting a total `duration`
across the clips) instead of having to set `start`/`duration` by hand on
each one. It's syntactic sugar: everything is translated into regular
`BinClipSpec` + `TrackSpec` *before* validation, so any overlap or duration
problem is caught by the same checks the rest of the pipeline uses.

## `transition: dissolve` — how it works

In MLT, two clips can't overlap within the same playlist. To get a real
dissolve (two clips visible at once, cross-fading) you need two separate
video tracks that overlap in time. So as soon as a scene asks for
`dissolve`, the compiler splits its clips across two alternating tracks
("Scenes A" / "Scenes B", shared by every scene in the document) with a
`transition_duration`-second overlap between consecutive clips.

The fade itself reuses the fade to/from black filter (`brightness` with
`alpha` keyframes) already used by `fade_in`/`fade_out`: an alpha of 0 on an
upper track doesn't paint black, it lets the track below show through, so it
works as a cross-fade. Only the clip that ends up on the "top" track in each
transition needs to carry the fade (the other stays opaque throughout: it's
revealed or covered solely by the alpha of the one on top).

Verified against a real `melt` render (not just structurally): a red clip
dissolving into a blue one produces a genuine, monotonic cross-fade
through the transition window, not a hard cut or a fade through black
(`tests/test_melt_validation.py::test_scenes_dissolve_produces_a_real_crossfade`).
That test needs a `melt` build with a working `qtblend` - dissolve is
inherently cross-track alpha compositing, so there's no way around that
dependency the way other tests avoid it (see conftest.py's
`melt_with_qtblend`).

## `transition: wipe` — how it works

Same alternating-track split as `dissolve`, but a *different* mechanism:
a wipe needs to decide, per pixel, which of the two overlapping clips
shows, driven by a grayscale "luma map" - that's a genuine two-source
comparison a per-clip alpha filter can't do. So instead of a fade filter,
each wipe overlap window becomes a `WipeTransitionSpec` (`models.py`),
which xmlgen.py turns into a real MLT `<transition mlt_service="luma">`
between the two tracks, scoped to exactly that window. Neither clip in a
wipe gets a fade - both stay fully opaque; the transition alone decides
visibility.

`luma:` on the scene picks the wipe shape, one of `lumas.AVAILABLE_LUMAS`
(default `linear_x`). Those are procedurally generated by this project
(plain gradient/angle/distance math, not copies of kdenlive's own
GPL-licensed luma maps - see `lumas.py`), so they're a similar but not
identical set to what kdenlive itself ships.

## `transition: affine` — how it works

A third transition engine, alongside `dissolve`'s alpha fade and `wipe`'s
luma map: MLT's own `affine` transition (Meltytech, LGPLv2.1, already
shipped with MLT - not a new dependency) geometrically transforms the
incoming ("b") clip's destination rectangle as it composites over the
outgoing one, driven by an `AffineTransitionSpec` the same way `wipe`
uses a `WipeTransitionSpec`. `style:` on the scene picks the
choreography:

- `zoom` (default): the incoming clip's rect grows from a tiny centered
  point (`50%/50%:1%x1%:100`) to the full frame (`0%/0%:100%x100%:100`) -
  a zoom-in reveal.
- `slide`: the incoming clip's rect starts fully off-frame to the right
  (`100%/0%:100%x100%:100`) and slides to fully cover the frame
  (`0%/0%:100%x100%:100`) - a push/slide-in reveal.

Both verified with real melt renders, not just structurally: `zoom`
against a center-vs-edge pixel sample, `slide` against a left-to-right
sweep sample (the same technique `wipe`'s own spatial test uses).
`spin`/`cube` (rotation, via `affine`'s `rotate_z`/`rotate_y`/
`fix_rotate_z`/`fix_rotate_y` properties) were investigated for this
cycle too, but empirically **don't work** on this project's real melt
build - those properties are accepted without error but only shrink the
destination rect's bounding box instead of actually rotating pixels
(checked directly: a rotated full-frame rect should expose the
background at its corners, and never did, keyframed or fixed, with
`fill`/`distort`/`rotate_center` toggled every way tried). Not shipped
until that's understood - see BACKLOG.md.

## Audio-only scenes

If every clip in a scene is audio, the compiler routes it to a *separate*
alternating track pair ("Scenes A (audio)" / "Scenes B (audio)") typed
`audio` instead of `video`, so fade_in/fade_out become volume fades (not
brightness alpha) and the overlap is summed by the a_track=0 `mix`
transition every audio track already gets (xmlgen.py) - same alternating-
track-overlap shape as the video case, but *not* the same fade
assignment: a video dissolve only needs the "top" clip in each pair to
fade (alpha compositing hides the bottom layer wherever the top is
opaque), while an audio dissolve is a genuine sum, so *both* the outgoing
and incoming clip need complementary fades or the un-faded one plays at
full volume and stops dead at its own boundary - an audible glitch, not a
crossfade (verified with a real render, two different tones one fading
into the other:
`tests/test_melt_validation.py::test_scenes_audio_dissolve_produces_a_real_crossfade`).
`transition: wipe`/`affine` have no audio equivalent (they transform or
mask pixels, not samples) and are rejected for an audio-only scene.

## Per-clip overrides (`mute`/`speed`/`position`/`size`)

A scene clip entry can be a dict instead of a bare path/`{clip: id}` -
`{clip: id, mute: true}` or `{path: '...', speed: 2.0}` - carrying the
same per-placement fields `timeline.tracks[].clips[]` already supports at
the low-level model, so reaching them doesn't force dropping out of
`scenes:` down to hand-written tracks (see `extract_clip_extras`).
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Optional

from . import probe
from .i18n import msg
from .lumas import AVAILABLE_LUMAS
from .models import (
    AFFINE_STYLES,
    AffineTransitionSpec,
    BinClipSpec,
    ClipPlacementSpec,
    ProjectDoc,
    TrackSpec,
    WipeTransitionSpec,
)

# Seconds per clip based on the scene's "pacing", if no `duration` is given.
# image: fixed duration. video_cap: upper bound (if the source clip is
# shorter than the cap, it's used whole, never stretched).
PACING_PRESETS = {
    "energetic": {"image": 1.5, "video_cap": 3.0},
    "normal": {"image": 3.0, "video_cap": 6.0},
    "slow": {"image": 5.0, "video_cap": 10.0},
}
DEFAULT_TRANSITION_DURATION = 1.0
DEFAULT_LUMA = "linear_x"
# "spin"/"cube" (rotate_z/rotate_y) were investigated for this cycle too,
# but this project's real melt build doesn't actually rotate pixels for
# them - fix_rotate_z/fix_rotate_y are accepted properties that only
# shrink the destination rect's bounding box, not a true per-pixel
# rotation (checked empirically: a rotated full-frame rect should expose
# background at its corners, and it never did, with or without keyframes,
# in isolation from the rest of this project). Not shipped until that's
# understood - see BACKLOG.md. "zoom" (rect scale) and "slide" (rect
# offset) don't need rotation and are verified working.
DEFAULT_AFFINE_STYLE = "zoom"
SCENE_TRACK_NAMES = (msg("scenes.track_a"), msg("scenes.track_b"))
# A separate alternating pair for scenes whose clips are *all* audio: audio
# tracks get volume fade filters (not brightness alpha), and the a_track=0
# `mix` transition every audio track already gets (see xmlgen.py) sums
# them together - so a "dissolve" between two audio clips just falls out
# of overlapping them on two tracks, no separate audio transition kind
# needed. `wipe` has no audio equivalent (a luma map decides pixels, not
# samples) - rejected instead, see compile_scenes.
SCENE_TRACK_NAMES_AUDIO = (msg("scenes.track_a_audio"), msg("scenes.track_b_audio"))


def compile_scenes(doc: ProjectDoc, scenes_data: list, errors: list[str]) -> ProjectDoc:
    if not scenes_data:
        return doc

    source_dir = doc.source_path.parent
    bin_by_id: dict[str, BinClipSpec] = {c.id: c for c in doc.bin}
    bin_by_path: dict[Path, BinClipSpec] = {c.path: c for c in doc.bin}
    new_bin: list[BinClipSpec] = list(doc.bin)

    def register_clip(raw: Any, ctx: str, idx: int) -> Optional[str]:
        """Accepts a path ('beach_01.jpeg'), {'clip': id, ...} referencing an
        id already defined in `bin:`, or {'path': '...', ...} - the dict
        forms may carry the same per-clip extras `_extract_clip_extras`
        reads (mute/speed/position/size/...). Bare paths (string or
        'path:') are auto-registered in the bin (id = filename without
        extension, disambiguated if needed)."""
        if isinstance(raw, dict) and "clip" in raw:
            clip_id = str(raw["clip"])
            if clip_id not in bin_by_id:
                errors.append(msg("validation.scene_clip_undefined", ctx=ctx, idx=idx, clip_id=clip_id))
                return None
            return clip_id

        path_str = raw["path"] if isinstance(raw, dict) and "path" in raw else raw
        if not isinstance(path_str, str):
            errors.append(msg("validation.scene_clip_invalid", ctx=ctx, idx=idx, raw=raw))
            return None

        candidate = (source_dir / path_str).resolve() if not Path(path_str).is_absolute() else Path(path_str)
        if candidate in bin_by_path:
            return bin_by_path[candidate].id

        clip_id = base_id = Path(path_str).stem
        n = 2
        while clip_id in bin_by_id:
            clip_id = f"{base_id}_{n}"
            n += 1
        spec = BinClipSpec(id=clip_id, path=candidate)
        new_bin.append(spec)
        bin_by_id[clip_id] = spec
        bin_by_path[candidate] = spec
        return clip_id

    def extract_clip_extras(raw: Any, ctx: str, idx: int) -> dict:
        """Per-clip overrides carried by the dict forms of a scene clip
        entry ({'clip': id, mute: true, ...} / {'path': ..., speed: 2.0}) -
        the same fields `timeline.tracks[].clips[]` already supports at the
        low-level, so a scene clip doesn't force dropping out of `scenes:`
        to reach them."""
        if not isinstance(raw, dict):
            return {}
        extras: dict = {}
        entry_ctx = f"{ctx}.clips[{idx}]"

        mute = raw.get("mute", False)
        if not isinstance(mute, bool):
            errors.append(msg("validation.mute_invalid", ctx=entry_ctx, mute=mute))
        else:
            extras["mute"] = mute

        if raw.get("speed") is not None:
            speed = float(raw["speed"])
            if speed == 0:
                errors.append(msg("validation.speed_zero", ctx=entry_ctx))
            else:
                extras["speed"] = speed
                extras["preserve_pitch"] = bool(raw.get("preserve_pitch", False))

        def pair(key: str) -> Optional[tuple[float, float]]:
            val = raw.get(key)
            if val is None:
                return None
            if not (isinstance(val, (list, tuple)) and len(val) == 2):
                errors.append(msg("validation.pair_invalid", ctx=entry_ctx, key=key))
                return None
            return (float(val[0]), float(val[1]))

        position = pair("position")
        if position is not None:
            extras["position"] = position
        size = pair("size")
        if size is not None:
            extras["size"] = size

        return extras

    track_clips: tuple[list[ClipPlacementSpec], list[ClipPlacementSpec]] = ([], [])
    track_clips_audio: tuple[list[ClipPlacementSpec], list[ClipPlacementSpec]] = ([], [])
    wipe_transitions: list[WipeTransitionSpec] = []
    affine_transitions: list[AffineTransitionSpec] = []
    cursor = 0.0  # global second at which the scenes block starts

    for s_idx, scene in enumerate(scenes_data):
        if not isinstance(scene, dict) or "clips" not in scene:
            errors.append(msg("validation.scene_missing_clips", idx=s_idx, scene=scene))
            continue
        name = scene.get("scene") or f"scene{s_idx}"
        ctx = f"scenes[{s_idx}]({name})"
        raw_clips = scene["clips"]
        if not isinstance(raw_clips, list) or not raw_clips:
            errors.append(msg("validation.scene_clips_not_list", ctx=ctx))
            continue

        transition = scene.get("transition", "none")
        if transition not in ("none", "dissolve", "wipe", "affine", "iris", "flip"):
            errors.append(msg("validation.scene_transition_invalid", ctx=ctx, transition=transition))
            continue
        overlap = (
            float(scene.get("transition_duration", DEFAULT_TRANSITION_DURATION))
            if transition in ("dissolve", "wipe", "affine", "iris", "flip")
            else 0.0
        )

        luma = scene.get("luma", DEFAULT_LUMA)
        if transition == "wipe" and luma not in AVAILABLE_LUMAS:
            errors.append(msg("validation.scene_luma_invalid", ctx=ctx, luma=luma, valid=list(AVAILABLE_LUMAS)))
            continue

        style = scene.get("style", DEFAULT_AFFINE_STYLE)
        if transition == "affine" and style not in AFFINE_STYLES:
            errors.append(msg("validation.scene_style_invalid", ctx=ctx, style=style, valid=list(AFFINE_STYLES)))
            continue

        pacing = scene.get("pacing", "normal")
        if pacing not in PACING_PRESETS:
            errors.append(msg("validation.scene_pacing_invalid", ctx=ctx, pacing=pacing, valid=list(PACING_PRESETS)))
            continue
        preset = PACING_PRESETS[pacing]

        clip_ids = [register_clip(raw, ctx, i) for i, raw in enumerate(raw_clips)]
        if any(c is None for c in clip_ids):
            continue
        n = len(clip_ids)
        clip_extras = [extract_clip_extras(raw, ctx, i) for i, raw in enumerate(raw_clips)]
        clip_kinds = [bin_by_id[cid].type or probe.guess_type(bin_by_id[cid].path) for cid in clip_ids]

        is_audio_scene = all(k == "audio" for k in clip_kinds)
        if transition in ("wipe", "affine", "iris", "flip") and is_audio_scene:
            errors.append(msg("validation.scene_transition_needs_video", ctx=ctx, transition=transition))
            continue
        active_track_clips = track_clips_audio if is_audio_scene else track_clips
        active_track_names = SCENE_TRACK_NAMES_AUDIO if is_audio_scene else SCENE_TRACK_NAMES

        explicit_duration = scene.get("duration")
        if explicit_duration is not None:
            per_clip = (float(explicit_duration) + (n - 1) * overlap) / n
            lengths = [per_clip] * n
        else:
            lengths = []
            probe_failed = False
            for i, (clip_id, kind) in enumerate(zip(clip_ids, clip_kinds)):
                spec = bin_by_id[clip_id]
                if kind == "image":
                    lengths.append(preset["image"])
                    continue
                try:
                    source_s = probe.probe_duration_seconds(str(spec.path))
                except probe.ProbeError as exc:
                    errors.append(f"{ctx}: {exc}")
                    probe_failed = True
                    continue
                # `speed` warps a clip's *usable* duration (schema.py
                # applies the same abs(speed) division) - the auto-pacing
                # cap has to compare against that warped length, not the
                # unwarped source, or a sped-up clip gets an `out:` beyond
                # what it actually has left on the warped timeline.
                speed = clip_extras[i].get("speed")
                warped_s = source_s / abs(speed) if speed else source_s
                lengths.append(min(warped_s, preset["video_cap"]))
            if probe_failed:
                continue

        start = cursor
        for i, (clip_id, length) in enumerate(zip(clip_ids, lengths)):
            if is_audio_scene and transition == "dissolve":
                # MLT's audio `mix` transition *sums* both tracks (unlike
                # qtblend's alpha compositing, which hides the bottom
                # layer wherever the top is opaque) - so a real audio
                # crossfade needs *both* the outgoing and incoming clip to
                # fade complementarily, not just the "top" one. Without
                # this, the un-faded clip plays at full volume and then
                # stops dead at its own boundary - an audible glitch, not
                # a crossfade (caught by
                # test_scenes_audio_dissolve_produces_a_real_crossfade).
                fade_in = overlap if i > 0 else None
                fade_out = overlap if i < n - 1 else None
            else:
                # With dissolve/iris/flip, only the "top" clip in each
                # transition carries the fade (or, for iris/flip, the
                # filter that stands in for one): it alternates, so it's
                # exactly the odd indices. Same mechanism as dissolve -
                # iris (frei0r.alphaspot) and flip (frei0r.3dflippo) are
                # single-clip filters composited via the qtblend this
                # project already emits per video track, not a genuine
                # two-source MLT transition like wipe/affine.
                is_top = transition in ("dissolve", "iris", "flip") and i % 2 == 1
                fade_in = overlap if (is_top and i > 0) else None
                fade_out = overlap if (is_top and i < n - 1) else None
            extras = clip_extras[i]
            placement = ClipPlacementSpec(
                clip=clip_id,
                start=start,
                in_=0.0,
                duration=length,
                fade_in=fade_in,
                fade_out=fade_out,
                mute=extras.get("mute", False),
                speed=extras.get("speed"),
                preserve_pitch=extras.get("preserve_pitch", False),
                position=extras.get("position"),
                size=extras.get("size"),
                reveal_style=transition if transition in ("iris", "flip") and is_top else None,
            )
            active_track_clips[i % 2].append(placement)
            # Neither wipe nor affine touches either clip's alpha (both
            # stay fully opaque) - the reveal comes entirely from a real
            # two-source MLT transition xmlgen.py adds between the
            # alternating tracks, scoped to exactly this overlap window.
            if transition == "wipe" and i > 0:
                wipe_transitions.append(
                    WipeTransitionSpec(
                        track_a=active_track_names[(i - 1) % 2],
                        track_b=active_track_names[i % 2],
                        start=start,
                        end=start + overlap,
                        luma=luma,
                    )
                )
            if transition == "affine" and i > 0:
                affine_transitions.append(
                    AffineTransitionSpec(
                        track_a=active_track_names[(i - 1) % 2],
                        track_b=active_track_names[i % 2],
                        start=start,
                        end=start + overlap,
                        style=style,
                    )
                )
            start += length - overlap

        cursor = start

    if errors:
        return doc

    tracks = list(doc.tracks)
    for name, clips in zip(SCENE_TRACK_NAMES, track_clips):
        if clips:
            tracks.append(TrackSpec(type="video", name=name, clips=clips))
    for name, clips in zip(SCENE_TRACK_NAMES_AUDIO, track_clips_audio):
        if clips:
            tracks.append(TrackSpec(type="audio", name=name, clips=clips))

    return ProjectDoc(
        project=doc.project,
        bin=new_bin,
        tracks=tracks,
        source_path=doc.source_path,
        raw_extras=doc.raw_extras,
        scenes_raw=[],
        wipe_transitions=doc.wipe_transitions + wipe_transitions,
        affine_transitions=doc.affine_transitions + affine_transitions,
        guides=doc.guides,
    )
