"""`sources.lock.yaml`: what `fetch` knows about each album item a project
uses, keyed by its original file name (BinClipSpec.source):

    items:
      PXL_20250830_085416309.mp4:
        media_id: AF1Qip...          # the album item it was found as
        size: 36322641
        sha256: f69c...
        taken: '2025-08-30T10:54:33' # capture time, local to where it was taken

Machine-written by `fetch` (one per directory, shared by a project and
its preview variants) and meant to be committed. Besides making later
fetches cheap, it's what the LOCAL file name of a `source:` clip comes
from: `<capture date>_<bin id><ext>` (see local_name), so `assets/`
reads like a dated list of what each file is, without the YAML having
to spell the date out.
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

import yaml

LOCK_NAME = "sources.lock.yaml"
_HEADER = "# Generated by `video-as-code fetch` - don't edit by hand.\n"


def read(base_dir: Path) -> dict[str, dict]:
    """The lock's items (original file name -> entry); {} if there's none."""
    path = base_dir / LOCK_NAME
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    items = data.get("items") if isinstance(data, dict) else None
    return dict(items) if isinstance(items, dict) else {}


def write(base_dir: Path, entries: dict[str, dict]) -> None:
    data = {"items": {name: entries[name] for name in sorted(entries)}}
    (base_dir / LOCK_NAME).write_text(
        _HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )


def taken_local(taken_ms: int, tz_offset_ms: int) -> str:
    """An album item's capture time as the lock records it: local wall
    time where it was taken, ISO format without offset."""
    when = datetime.fromtimestamp((taken_ms + tz_offset_ms) / 1000, timezone.utc)
    return when.strftime("%Y-%m-%dT%H:%M:%S")


def local_name(clip_id: str, source: str, entry: Optional[dict], override: Optional[str] = None) -> str:
    """The file name a `source:` clip is stored under locally: `override`
    (the clip's `local_name:`) if given; else `<YYYYMMDD>_<clip id><ext>`
    from the capture date in the lock (the extension is the original's,
    lower-cased); else - not fetched yet, so the date isn't known - the
    original name itself, which simply won't exist and gets reported as
    "not fetched"."""
    if override:
        return override
    taken = (entry or {}).get("taken")
    if not taken:
        return source
    return f"{str(taken)[:10].replace('-', '')}_{clip_id}{Path(source).suffix.lower()}"
