"""Bundled luma maps for `transition: wipe` (scenes.py) - tiny grayscale
PNGs, one per wipe shape, checked into the package itself so `video-as-code
build`/`render` don't need kdenlive installed at all.

These are procedurally generated by us (linear/radial/angle/checkerboard
gradients - plain math, computed once and saved as PGMs under
`lumas_data/`), not copies of kdenlive's own bundled luma maps:
kdenlive's are GPL-licensed, and this project doesn't declare a
GPL-compatible license, so redistributing them here would be a real
entanglement. The shapes are inspired by kdenlive's own naming (same wipe
styles editors expect) but the pixels are ours.

PGM, not PNG: MLT's `luma` transition parses `.pgm` luma maps directly
(`mlt_luma_map_from_pgm`); anything else goes through a generic
image-loader producer path instead, and empirically that path produced a
near-instant cut instead of a gradual wipe for the same gradient (see
`tests/test_melt_validation.py::test_scenes_wipe_produces_a_real_spatial_wipe`
and its neighboring comment) - not worth chasing why when the direct PGM
path just works. Kept tiny (64x64 - MLT scales the map to the actual
frame size at render time, so resolution here doesn't need to match the
project's) to stay in line with this repo's tiny-committed-assets
precedent."""
from __future__ import annotations

from pathlib import Path

LUMAS_DIR = Path(__file__).parent / "lumas_data"

AVAILABLE_LUMAS = (
    "linear_x",
    "linear_y",
    "diagonal",
    "radial",
    "square",
    "clock",
    "spiral",
    "bars_horizontal",
    "bars_vertical",
    "checkerboard",
    "heart",
    "bowtie",
)


def luma_path(name: str) -> Path:
    return LUMAS_DIR / f"{name}.pgm"
